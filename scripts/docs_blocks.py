"""Check the documentation conventions that a generator cannot enforce.

Counts the Python code blocks under ``docs/`` and checks that every skipped block gives a
reason: a block is skipped with ```` ```{.python notest} ```` and must be preceded, on the
line immediately above, by ``<!-- notest: reason -->``. Pages under ``docs/examples/`` are
rendered from ``examples/*.py``, which are tested as files, so they are not counted.

Also checks that ``docs/AGENTS.md`` exists and stays in step with the generated pages: every
page carrying a ``Generated by <script>`` marker must be named in the guide together with its
generator, and every generator the guide names must exist.

Refuses a parameter default computed at import, such as ``day=date.today()``, in
``examples/*.py`` and in tested blocks: a default is evaluated once, and the server copies
the value it registered into every scheduled run. A constructor called by name with only
literal arguments, such as ``date(2026, 3, 1)``, is a constant and allowed. Prints
``docs: N blocks tested, M skipped`` and exits non-zero on a violation.
"""

from __future__ import annotations

import ast
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
FENCE = re.compile(r"^```(\{\.?(?P<lang_b>[\w+-]+)(?P<opts>[^}]*)\}|(?P<lang>[\w+-]+)(?P<rest>.*))?\s*$")
REASON = re.compile(r"^<!--\s*notest:\s*\S.*-->\s*$")
MARKER = re.compile(r"<!--\s*Generated by (?P<script>\S+\.py)\b")
GUIDE = os.path.join(DOCS, "AGENTS.md")
GENERATOR = re.compile(r"`(?P<script>scripts/\S+\.py)`")


def check_guide(problems: list[str]) -> None:
    """`docs/AGENTS.md` must exist and list every generated page with its generator."""
    rel = os.path.relpath(GUIDE, ROOT)
    if not os.path.exists(GUIDE):
        problems.append(
            f"{rel}: missing; the authoring guide is what contributors and agents read"
            " before adding or changing a page under docs/"
        )
        return
    guide = open(GUIDE, encoding="utf-8").read()
    for path in sorted(glob.glob(os.path.join(DOCS, "**", "*.md"), recursive=True)):
        head = "".join(open(path, encoding="utf-8").readlines()[:10])
        m = MARKER.search(head)
        if not m:
            continue
        page = os.path.relpath(path, ROOT)
        script = m.group("script")
        if page not in guide:
            problems.append(f"{rel}: does not name the generated page {page}")
        elif script not in guide:
            problems.append(f"{rel}: names {page} without its generator {script}")
    for script in sorted(set(GENERATOR.findall(guide))):
        if not os.path.exists(os.path.join(ROOT, script)):
            problems.append(f"{rel}: names {script}, which does not exist")


def _constant_call(node: ast.Call) -> bool:
    """`date(2026, 3, 1)`: a call by plain name whose arguments are all literals."""
    args = list(node.args) + [k.value for k in node.keywords]
    return (
        isinstance(node.func, ast.Name)
        and bool(args)
        and all(isinstance(a, ast.Constant) or (isinstance(a, ast.UnaryOp) and isinstance(a.operand, ast.Constant)) for a in args)
    )


def computed_defaults(source: str) -> list[tuple[int, str, str]]:
    """Parameter defaults that call something at import: (line, function, parameter)."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    found: list[tuple[int, str, str]] = []
    for fn in ast.walk(tree):
        if not isinstance(fn, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            continue
        a = fn.args
        positional = a.posonlyargs + a.args
        pairs = list(zip(positional[len(positional) - len(a.defaults):], a.defaults))
        pairs += [(arg, d) for arg, d in zip(a.kwonlyargs, a.kw_defaults) if d is not None]
        for arg, default in pairs:
            for node in ast.walk(default):
                if isinstance(node, ast.Call) and not _constant_call(node):
                    name = getattr(fn, "name", "<lambda>")
                    found.append((default.lineno, name, arg.arg))
                    break
    return found


def check_defaults(source: str, rel: str, offset: int, problems: list[str]) -> None:
    for line, fn, param in computed_defaults(source):
        problems.append(
            f"{rel}:{line + offset}: `{fn}` computes the default of `{param}` at import;"
            " the server reuses the registered value for every run, so default to None"
            " and work the value out in a task"
        )


def main() -> int:
    tested = skipped = 0
    problems: list[str] = []
    check_guide(problems)
    for path in sorted(glob.glob(os.path.join(ROOT, "examples", "*.py"))):
        check_defaults(open(path, encoding="utf-8").read(), os.path.relpath(path, ROOT), 0, problems)
    for path in sorted(glob.glob(os.path.join(DOCS, "**", "*.md"), recursive=True)):
        if os.path.relpath(path, DOCS).startswith("examples" + os.sep):
            continue
        lines = open(path, encoding="utf-8").read().splitlines()
        inside = False
        block: list[str] | None = None
        start = 0
        for n, line in enumerate(lines):
            m = FENCE.match(line)
            if not m:
                if block is not None:
                    block.append(line)
                continue
            if inside:
                inside = False
                if block is not None:
                    check_defaults("\n".join(block), os.path.relpath(path, ROOT), start, problems)
                    block = None
                continue
            inside = True
            lang = m.group("lang_b") or m.group("lang") or ""
            opts = (m.group("opts") or m.group("rest") or "").split()
            if lang not in ("python", "py", "python3"):
                continue
            if "notest" in opts:
                skipped += 1
                if n == 0 or not REASON.match(lines[n - 1]):
                    problems.append(f"{os.path.relpath(path, ROOT)}:{n + 1}: notest block without a `<!-- notest: reason -->` line above it")
            else:
                tested += 1
                block, start = [], n + 1
    for p in problems:
        print(p)
    print(f"docs: {tested} blocks tested, {skipped} skipped")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
